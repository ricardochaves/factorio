# Every language defines the same keys. Without this check a missing key fails the build only on the page that uses it.
_differ = {lang: sorted(set(T[DEFAULT]) ^ set(T[lang])) for lang in LANGS if set(T[lang]) != set(T[DEFAULT])}
if _differ:
    raise SystemExit(f'i18n: the keys of these languages differ from {DEFAULT}: {_differ}')


def label(d, lang):
    """d is one of the {'pt': ..., 'en': ..., 'es': ...} dicts above."""
    return d.get(lang) or d[DEFAULT]


def fmt_int(n, lang):
    """Same grouping as the browser's toLocaleString (CLDR): Spanish does not group 4-digit numbers (RAE)."""
    if lang == 'es' and abs(n) < 10000:
        return str(n)
    s = f'{n:,}'
    return s if lang == 'en' else s.replace(',', '.')


def fmt_bytes(n, lang):
    s = f'{n / 1e6:.1f} MB' if n >= 1e6 else f'{max(1, round(n / 1e3))} kB'
    return s if lang == 'en' else s.replace('.', ',')


def fmt_date(d, lang):
    """d is a datetime.date."""
    m = MONTHS[lang][d.month - 1]
    return f'{m} {d.day}, {d.year}' if lang == 'en' else f'{d.day} {m} {d.year}'
